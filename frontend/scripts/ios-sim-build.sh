#!/usr/bin/env bash
# Builds the app for the iOS simulator in the Release configuration, so the JS runs as
# Hermes bytecode with no Metro server, the way it ships.
#
#   scripts/ios-sim-build.sh screenshots   Storybook screenshot harness (ClickUp 86bcxruz4):
#                                          bundles .rnstorybook/screenshots as the entry.
#   scripts/ios-sim-build.sh e2e           The real app, pointed at the E2E stack
#                                          (ClickUp 86bcxruy6): Auth emulator on 9199,
#                                          API on $E2E_API_PORT (default 8090).
#
# Output: build/ios/<variant>/ActiveQueue.app. ios/ is generated by `expo prebuild` and
# gitignored; CLEAN_PREBUILD=1 regenerates it. Needs Xcode and CocoaPods.
set -euo pipefail

variant="${1:?usage: $0 screenshots|e2e}"
cd "$(dirname "$0")/.."
root="$PWD"

case "$variant" in
  screenshots)
    # The Xcode bundle phase only resolves the expo-router entry when ENTRY_FILE is unset.
    export ENTRY_FILE="$root/.rnstorybook/screenshots/index.tsx"
    ;;
  e2e)
    # Inlined into the bundle at build time. EXPO_PUBLIC_USE_EMULATOR turns on the Auth
    # emulator and the dev sign-in in a Release build (src/core/config/devTools.ts).
    export EXPO_PUBLIC_USE_EMULATOR=true
    export EXPO_PUBLIC_API_URL="http://127.0.0.1:${E2E_API_PORT:-8090}"
    export EXPO_PUBLIC_FIREBASE_AUTH_EMULATOR_HOST="http://127.0.0.1:9199"
    export EXPO_PUBLIC_FIREBASE_PROJECT_ID="demo-activequeue-local"
    ;;
  *)
    echo "usage: $0 screenshots|e2e" >&2
    exit 2
    ;;
esac

if [[ ! -d ios || "${CLEAN_PREBUILD:-0}" == "1" ]]; then
  CI=1 npx expo prebuild --platform ios --clean --no-install
fi
(cd ios && pod install)

log="build/xcodebuild-$variant.log"
mkdir -p build
echo "ios-sim-build: building $variant (log: $log)"
# IPHONEOS_DEPLOYMENT_TARGET: Xcode 27 rejects pod resource targets that still declare
# iOS 12/13 (RNSVG, AsyncStorage). 15.1 is Expo SDK 54's own floor.
if ! xcodebuild \
  -workspace ios/ActiveQueue.xcworkspace \
  -scheme ActiveQueue \
  -configuration Release \
  -sdk iphonesimulator \
  -destination 'generic/platform=iOS Simulator' \
  -derivedDataPath build/dd \
  CODE_SIGNING_ALLOWED=NO \
  IPHONEOS_DEPLOYMENT_TARGET=15.1 \
  > "$log" 2>&1; then
  grep -E ' error:|error: ' "$log" | head -40 >&2 || tail -60 "$log" >&2
  exit 1
fi

out="build/ios/$variant"
rm -rf "$out"
mkdir -p "$out"
cp -R build/dd/Build/Products/Release-iphonesimulator/ActiveQueue.app "$out/"
echo "ios-sim-build: $out/ActiveQueue.app"
